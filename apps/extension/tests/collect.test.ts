/**
 * @vitest-environment jsdom
 */
import { describe, expect, it } from "vitest";
import { PageSnapshotSchema } from "@vibetrace/shared-types";
import { collectPageSnapshot } from "../src/content/collect.js";

function preparePage(): void {
  window.history.replaceState({}, "", "/dashboard?token=URL_SECRET#fragment");
  document.head.innerHTML = [
    '<meta charset="utf-8">',
    '<meta name="generator" content="Lovable">',
    '<meta name="description" content="AI-assisted dashboard. Contact alice@example.com">',
    '<meta name="csrf-token" content="CSRF_SECRET">',
    '<meta name="author" content="Alice Private">',
    '<meta property="og:title" content="Atlas Workspace">',
    '<link rel="stylesheet" href="/assets/app.css?v=STYLE_SECRET">',
    '<script type="application/ld+json">{"@context":"https://schema.org","@type":"WebApplication","name":"Atlas"}</script>',
  ].join("");
  document.documentElement.lang = "en";
  document.title = "Atlas Workspace";
  document.body.innerHTML = [
    "<header><nav><h1>Atlas Workspace</h1><h2>Private account heading</h2>",
    '<a href="https://external.example/docs?token=LINK_SECRET">Documentation</a>',
    '<a href="mailto:alice@example.com?subject=Private">Contact sales</a>',
    '<a href="javascript:alert(1)">Unsafe link</a></nav></header>',
    "<main>",
    '<img src="/assets/hero.png?token=IMAGE_SECRET" alt="Dashboard hero" width="640" height="360">',
    '<img src="data:image/png;base64,SECRETDONOTUPLOAD">',
    '<form action="/submit?token=FORM_SECRET">',
    '<label for="email">Email</label><input id="email" name="email" type="email" value="user@example.com">',
    '<label for="password">Password</label><input id="password" name="password" type="password" value="hunter2-SECRET">',
    '<input type="hidden" name="csrf" value="HIDDEN_SECRET">',
    '<button type="submit">Save changes</button>',
    "</form>",
    '<div class="min-h-screen bg-slate-950 flex" style="background-image:url(SECRET_BG)" data-secret="DATA_SECRET">Unrelated private body text</div>',
    '<div class="grid gap-4 v0-panel" data-wf-site="site-id" data-testid="internal-test-id"></div>',
    '<iframe src="https://evil.example/frame?token=IFRAME_SECRET"></iframe>',
    '<script src="/assets/app.js?token=SCRIPT_SECRET"></script>',
    '<script>const key = "sk-abcdefghijklmnopqrstuvwxyz123456"; // Generated by v0 for Lovable</script>',
    "<!-- Built with Lovable and deployed on Vercel -->",
    "<!-- customer note: alice@example.com private -->",
    "</main>",
  ].join("");
}

describe("extension snapshot collector", () => {
  it("produces a schema-valid, sanitized snapshot", () => {
    preparePage();
    const snapshot = collectPageSnapshot();
    const parsed = PageSnapshotSchema.safeParse(snapshot);
    expect(parsed.success).toBe(true);
    expect(snapshot.url).toBe("http://localhost:3000/dashboard");
    expect(snapshot.title).toBe("Atlas Workspace");
    expect(snapshot.lang).toBe("en");
    expect(snapshot.dom.headingLevels).toEqual([1, 2]);
    expect(snapshot.dom.imageCount).toBe(2);
    expect(snapshot.dom.imagesWithAlt).toBe(1);
    expect(snapshot.dom.inputCount).toBe(2);
    expect(snapshot.dom.labeledInputCount).toBe(2);
    expect(snapshot.dom.buttonCount).toBe(1);
    expect(snapshot.dom.linkCount).toBe(3);
    expect(snapshot.dom.semanticElements).toContain("main");
    expect(snapshot.dom.semanticElements).toContain("nav");
    expect(snapshot.dom.classSignatureSamples.some((value) => value.includes("v0-panel"))).toBe(
      true,
    );
    expect(snapshot.dom.htmlComments).toContain("Built with Lovable and deployed on Vercel");
    expect(snapshot.dom.inlineScriptCount).toBeGreaterThanOrEqual(1);
  });

  it("never includes form values, cookies, storage, hidden fields or unrelated text", () => {
    preparePage();
    const serialized = JSON.stringify(collectPageSnapshot());
    for (const secret of [
      "hunter2-SECRET",
      "user@example.com",
      "HIDDEN_SECRET",
      "CSRF_SECRET",
      "DATA_SECRET",
      "SECRET_BG",
      "Unrelated private body text",
      "Alice Private",
      "internal-test-id",
    ]) {
      expect(serialized).not.toContain(secret);
    }
    expect(serialized).not.toContain("IFRAME_SECRET");
    expect(serialized).not.toContain("<iframe");
    expect(serialized).not.toContain("javascript:");
    expect(serialized).not.toContain("style=");
  });

  it("strips query strings and fragments from collected URLs", () => {
    preparePage();
    const snapshot = collectPageSnapshot();
    expect(snapshot.url).not.toContain("URL_SECRET");
    expect(snapshot.url).not.toContain("?");
    expect(snapshot.scriptSources).toEqual(["http://localhost:3000/assets/app.js"]);
    expect(snapshot.stylesheetHrefs).toEqual(["http://localhost:3000/assets/app.css"]);
    expect(snapshot.dom.imageSources).toEqual(["http://localhost:3000/assets/hero.png"]);
    expect(snapshot.html).not.toContain("IMAGE_SECRET");
    expect(snapshot.html).not.toContain("SCRIPT_SECRET");
    expect(snapshot.html).not.toContain("FORM_SECRET");
    expect(snapshot.html).not.toContain("LINK_SECRET");
    expect(snapshot.html).not.toContain("mailto:");
    expect(snapshot.html).not.toContain("alice@example.com");
  });

  it("keeps only technical metadata and redacts personal data", () => {
    preparePage();
    const snapshot = collectPageSnapshot();
    expect(snapshot.meta.generator).toBe("Lovable");
    expect(snapshot.meta.description).toContain("[email]");
    expect(snapshot.meta["csrf-token"]).toBeUndefined();
    expect(snapshot.meta.author).toBeUndefined();
    expect(snapshot.meta["og:title"]).toBe("Atlas Workspace");
    expect(snapshot.dom.jsonLdSamples).toHaveLength(1);
  });

  it("collects bounded technical script excerpts and redacts credentials", () => {
    preparePage();
    const snapshot = collectPageSnapshot();
    expect(snapshot.dom.inlineScriptSamples.length).toBeGreaterThan(0);
    const sample = snapshot.dom.inlineScriptSamples.join("\n");
    expect(sample).toContain("Generated by v0");
    expect(sample).not.toContain("sk-abcdefghijklmnopqrstuvwxyz123456");
    expect(sample).toContain("[redacted-key]");
    expect(snapshot.html).not.toContain("Generated by v0");
  });

  it("keeps the DOM skeleton compact and accessibility-relevant", () => {
    preparePage();
    const snapshot = collectPageSnapshot();
    expect(snapshot.html.length).toBeLessThan(480_000);
    expect(snapshot.html).toContain("<h1>Atlas Workspace</h1>");
    expect(snapshot.html).toContain('alt="Dashboard hero"');
    expect(snapshot.html).toContain('id="email"');
    expect(snapshot.html).toContain("Save changes");
    expect(snapshot.html).not.toContain("<script");
    expect(snapshot.html).not.toContain("<style");
    expect(snapshot.dom.maxDepth).toBeGreaterThan(2);
    expect(snapshot.dom.nodeCount).toBeGreaterThan(10);
  });
});
